/**
 * Pi CLI Extension: Destructive Bash Command Guard
 *
 * Intercepts tool_call events for `bash`. If a command matches a danger rule
 * (recursive deletion, destructive git, disk operations, elevated privileges,
 * pipe-to-shell, secret exfiltration, ...), it pauses execution and asks for approval.
 *
 * In Hive Studio the approval is an inline card above the composer (the confirm
 * body is a JSON `dangerous_bash_approval` payload, see src/shared.ts).
 * In headless mode (no UI) a flagged command is blocked.
 *
 * Jev tier (active when the Jev module has an API key and consent, or JEV_GUARD_ENABLED=1 + JEV_API_KEY;
 * JEV_GUARD_ENABLED=0 turns it off):
 *  - Triage: a moderate/high rule hit is sent (redacted) to Jev; a clearly routine answer skips the prompt.
 *    Critical rule hits always prompt. BASH_GUARD_TRIAGE=0 turns triage off.
 *  - Judge: commands the rules did not recognise (and not on the read-only allowlist) are sent to Jev;
 *    a risky answer escalates to a prompt.
 *  Any Jev failure leaves a rule hit as a prompt and allows an unrecognised command (rules still protect).
 *
 * Describer: a prompt carries a plain-language summary written by a cheap model through Pi's own provider
 * keys (see src/describe.ts). Display-only; falls back to the rule text.
 *
 * This file is the bundling entry for agent/extensions/bash-guard.ts, which is GENERATED by
 * scripts/build-extension.mjs: only `import type` from the Pi package may be used outside
 * src/engine, src/jev.ts, src/describe.ts and src/extension/triage-log.ts, because Pi copies the generated file verbatim.
 */

import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";
import { analyzeCommand } from "../engine/analyze.ts";
import { decideFromJev, shouldJudge, type JevAnswers } from "../engine/judge.ts";
import { triageRuleHit } from "../engine/triage.ts";
import { describeCommand, describerEnabled, type Description, type DescribeRegistry } from "../describe.ts";
import { askJev, readJevConfig } from "../jev.ts";
import { logTriageSkip } from "./triage-log.ts";

interface Flag {
  severity: "critical" | "high" | "moderate";
  ruleId: string;
  ruleTitle: string;
  reason: string;
  matchedSegment: string;
  source: "rule" | "jev";
}

const OFF = /^(0|false|no|off)$/i;

export default function bashGuard(pi: ExtensionAPI): void {
  pi.on("tool_call", async (event, ctx) => {
    if (event.toolName !== "bash") return undefined;

    const command = (event.input as { command?: string })?.command ?? "";
    if (!command.trim()) return undefined;

    const env = process.env;
    const log = (m: string) => console.error(m);
    const jevCfg = readJevConfig(env);
    const anyCtx = ctx as unknown as { modelRegistry?: DescribeRegistry; cwd?: string; model?: { provider?: string } };
    const abort = new AbortController();
    const describe = (ruleTitle: string): Promise<Description | null> =>
      ctx.hasUI && describerEnabled(env, jevCfg.enabled)
        ? describeCommand(command, { registry: anyCtx.modelRegistry, env, cwd: anyCtx.cwd ?? ctx.cwd, ruleTitle, currentProvider: anyCtx.model?.provider, signal: abort.signal, log })
        : Promise.resolve(null);

    let flag: Flag | null = null;
    let answers: JevAnswers | null = null;
    let description: Description | null = null;

    const hit = analyzeCommand(command);
    if (hit) {
      flag = { severity: hit.severity, ruleId: hit.id, ruleTitle: hit.title, reason: hit.reason, matchedSegment: hit.matchedSegment, source: "rule" };
      // Start the description now; it runs while Jev answers, and is dropped when the prompt is skipped.
      const described = describe(hit.title);
      if (jevCfg.enabled && hit.severity !== "critical" && !OFF.test(env.BASH_GUARD_TRIAGE ?? "")) {
        answers = await askJev(command, { log });
        const triage = triageRuleHit(hit.severity, answers);
        if (triage.action === "skip") {
          abort.abort();
          logTriageSkip({ command, ruleId: hit.id, severity: hit.severity, risk: answers?.risk, approval: answers?.approval, reason: triage.reason }, env);
          return undefined;
        }
      }
      description = await described;
    } else if (jevCfg.enabled && shouldJudge(command, false)) {
      // Jev tier: unknown command. Never throws; null = unreachable -> allow and log.
      answers = await askJev(command, { log });
      const verdict = decideFromJev(answers);
      if (verdict.confirm) {
        flag = { severity: verdict.severity, ruleId: "jev-judge", ruleTitle: "Flagged by Jev risk assessment", reason: verdict.reason, matchedSegment: command, source: "jev" };
        description = await describe(flag.ruleTitle);
      }
    }
    if (!flag) return undefined;

    const jev =
      answers && (typeof answers.risk === "number" || typeof answers.approval === "number")
        ? { ...(typeof answers.risk === "number" ? { risk: answers.risk } : {}), ...(typeof answers.approval === "number" ? { approval: answers.approval } : {}) }
        : undefined;

    const payload = JSON.stringify({
      kind: "dangerous_bash_approval",
      command,
      severity: flag.severity,
      ruleId: flag.ruleId,
      ruleTitle: flag.ruleTitle,
      reason: flag.reason,
      matchedSegment: flag.matchedSegment,
      source: flag.source,
      ...(description ? { description } : {}),
      ...(jev ? { jev } : {}),
    });

    if (!ctx.hasUI) {
      return {
        block: true,
        reason: `Destructive bash command blocked automatically in headless mode: ${flag.reason} (${command})`,
      };
    }

    const title = `⚠️ Dangerous Bash Command: ${flag.ruleTitle}`;
    const confirmed = await ctx.ui.confirm(title, payload);

    if (!confirmed) {
      return {
        block: true,
        reason: `Command execution blocked by user: ${flag.reason}`,
      };
    }

    return undefined;
  });
}
